def build_external_env(base_env: Optional[dict] = None) -> dict:
    """Build an environment for external subprocesses (vendor CLIs, git, test commands).

    Guarantees install-root PYTHONPATH does not leak into external processes (review-r3 Finding 1).
    Restores caller's original PYTHONPATH from _MESH_ORIG_PYTHONPATH or unsets it.
    Strips all MESH_* variables per plan §11.1 step 2.
    """
    import os

    if base_env is None:
        base_env = os.environ
    env = dict(base_env)

    # Strip every MESH_* variable per plan §11.1
    for k in list(env.keys()):
        if k.startswith("MESH_"):
            del env[k]

    # Restore caller's original PYTHONPATH (review-r3 Finding 1)
    orig_pythonpath = env.pop("_MESH_ORIG_PYTHONPATH", None)
    if orig_pythonpath is not None:
        if orig_pythonpath == "__UNSET__":
            env.pop("PYTHONPATH", None)
        else:
            env["PYTHONPATH"] = orig_pythonpath

    return env
