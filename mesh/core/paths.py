def mesh_cli_argv(*args: str) -> List[str]:
    """Return argv to invoke Mesh CLI directly via the active Python interpreter."""
    return [sys.executable, "-P", "-s", "-m", "mesh", *args]


def get_install_root() -> str:
    """Return the absolute real path of the Mesh install root.

    The install root contains bin/mesh and the mesh/ package directory.
    """
    # mesh/core/paths.py -> mesh/core -> mesh -> install_root
    core_dir = os.path.dirname(os.path.abspath(__file__))
    mesh_pkg_dir = os.path.dirname(core_dir)
    install_root = os.path.dirname(mesh_pkg_dir)
    return os.path.realpath(install_root)


def is_site_packages_dir(path: str) -> bool:
    """Return True if *path* is an active global site-packages directory.

    Only directories reported by ``site.getsitepackages()`` are searched when
    Python runs with ``-P -s``; ``-s`` disables user site-packages and custom
    target directories still require ``PYTHONPATH`` to import ``mesh``.
    """
    if not path:
        return False
    import site

    real = norm_cmp(os.path.realpath(path))
    global_dirs = {norm_cmp(os.path.realpath(sp)) for sp in site.getsitepackages() if sp}
    return real in global_dirs


def _cmd_escape_pct(value: str) -> str:
    return value.replace("%", "%%")


def _build_win_mesh_cmd_body(root: str, executable: str, site_pkg: bool) -> str:
    pp_line = 'set "PYTHONPATH="\r\n' if site_pkg else f'set "PYTHONPATH={_cmd_escape_pct(root)}"\r\n'
    exe = _cmd_escape_pct(executable)
    return (
        "@echo off\r\n"
        "rem Generated by Agent Mesh for a package install; safe to delete.\r\n"
        "setlocal EnableExtensions\r\n"
        "if not defined _MESH_ORIG_PYTHONPATH (\r\n"
        '  if defined PYTHONPATH (set "_MESH_ORIG_PYTHONPATH=%PYTHONPATH%") else (set "_MESH_ORIG_PYTHONPATH=__UNSET__")\r\n'
        ")\r\n"
        f"{pp_line}"
        f'"{exe}" -P -s -m mesh %*\r\n'
        "exit /b %ERRORLEVEL%\r\n"
    )


def _write_shim_if_changed(
    shim_path: str,
    body: str,
    bin_dir: str,
    *,
    mode: int = 0o700,
    newline: Optional[str] = None,
) -> None:
    import tempfile

    try:
        with open(shim_path, "r", encoding="utf-8", newline="") as f:
            if f.read() == body:
                return
    except OSError:
        pass
    fd, tmp = tempfile.mkstemp(dir=bin_dir, prefix=".mesh-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline=newline) as f:
            f.write(body)
        if sys.platform == "win32":
            perms.set_private_file_acl(tmp, mode)
        else:
            os.chmod(tmp, mode)
        atomic_replace(tmp, shim_path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def get_mesh_bin_dir() -> str:
    """Directory holding a ``mesh`` executable for this install (productize).

    From a clone this is ``<install_root>/bin``. A package install (pipx, ``uv tool``,
    ``pip install .``) has no ``bin/mesh`` next to the package, so a small shim that runs
    this interpreter on this package is written to ``$XDG_CACHE_HOME/agent-mesh/bin``
    (default ``~/.cache/agent-mesh/bin``, mode 0700) on POSIX or
    ``%LOCALAPPDATA%\\agent-mesh\\bin`` on Windows. meshd puts this directory first on
    launched agents' PATH and starts itself through it.
    """
    root = get_install_root()
    clone_bin = os.path.join(root, "bin")
    if sys.platform == "win32":
        if os.path.isfile(os.path.join(clone_bin, "mesh.cmd")):
            return clone_bin
    elif os.path.isfile(os.path.join(clone_bin, "mesh")):
        return clone_bin

    import hashlib
    import shlex
    import tempfile

    ident = hashlib.sha256("\0".join((os.path.realpath(root), os.path.abspath(sys.executable),
                                       os.path.realpath(sys.executable), os.path.abspath(sys.prefix))
                                      ).encode()).hexdigest()[:16]
    site_pkg = is_site_packages_dir(root)

    if sys.platform == "win32":
        cache = (
            os.environ.get("LOCALAPPDATA")
            or os.environ.get("XDG_CACHE_HOME")
            or os.path.join(os.path.expanduser("~"), "AppData", "Local")
        )
        bin_dir = os.path.join(cache, "agent-mesh", "bin", ident)
        existed = os.path.isdir(bin_dir)
        os.makedirs(bin_dir, mode=0o700, exist_ok=True)
        if not existed:
            perms.set_private_dir_acl(bin_dir, 0o700)
        cmd_shim = os.path.join(bin_dir, "mesh.cmd")
        cmd_body = _build_win_mesh_cmd_body(root, sys.executable, site_pkg)
        _write_shim_if_changed(cmd_shim, cmd_body, bin_dir, mode=0o700, newline="")

        sh_shim = os.path.join(bin_dir, "mesh")
        sh_pp = (
            "unset PYTHONPATH\n"
            if site_pkg
            else f"export PYTHONPATH={shlex.quote(root)}\n"
        )
        sh_body = (
            "#!/bin/sh\n# Generated by Agent Mesh for a package install; safe to delete.\n"
            "if [ -z \"${_MESH_ORIG_PYTHONPATH+x}\" ]; then export _MESH_ORIG_PYTHONPATH=\"${PYTHONPATH:-__UNSET__}\"; fi\n"
            f"{sh_pp}"
            f"exec {shlex.quote(sys.executable)} -P -s -m mesh \"$@\"\n"
        )
        _write_shim_if_changed(sh_shim, sh_body, bin_dir, mode=0o700, newline="\n")
        return bin_dir

    cache = os.environ.get("XDG_CACHE_HOME") or os.path.join(os.path.expanduser("~"), ".cache")
    # One shim per installation (package root + interpreter), so two virtual environments
    # sharing HOME never overwrite each other's launcher (Linear round 3 P2).
    bin_dir = os.path.join(cache, "agent-mesh", "bin", ident)
    os.makedirs(bin_dir, mode=0o700, exist_ok=True)
    shim = os.path.join(bin_dir, "mesh")
    pp_line = (
        "unset PYTHONPATH\n"
        if site_pkg
        else f"export PYTHONPATH={shlex.quote(root)}\n"
    )
    body = ("#!/bin/sh\n# Generated by Agent Mesh for a package install; safe to delete.\n"
            "if [ -z \"${_MESH_ORIG_PYTHONPATH+x}\" ]; then export _MESH_ORIG_PYTHONPATH=\"${PYTHONPATH:-__UNSET__}\"; fi\n"
            f"{pp_line}"
            f"exec {shlex.quote(sys.executable)} -P -s -m mesh \"$@\"\n")
    try:
        with open(shim, "r", encoding="utf-8") as f:
            if f.read() == body:
                return bin_dir
    except OSError:
        pass
    fd, tmp = tempfile.mkstemp(dir=bin_dir, prefix=".mesh-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(body)
    os.chmod(tmp, 0o700)
    os.replace(tmp, shim)
    return bin_dir


def _resolve_path_win(joined: str) -> str:
    """Resolve symlinks/junctions before folding ``..`` on Windows.

    CPython's ``ntpath.realpath`` calls ``normpath``/lexical normalization before
    dereferencing symlinks, turning ``a/link/..`` into ``a`` instead of the link
    target's parent. Walk components and canonicalize each existing prefix before
    handling ``..``.
    """
    drive, tail = os.path.splitdrive(joined)
    if tail.startswith(("/", "\\")):
        cur = (drive + "\\") if drive else (os.path.splitdrive(os.getcwd())[0] + "\\")
    else:
        cur = os.getcwd()
    for part in re.split(r"[/\\]+", tail):
        if not part or part == ".":
            continue
        if part == "..":
            if os.path.lexists(cur):
                cur = os.path.realpath(cur)
            parent = os.path.dirname(cur)
            cur = parent if parent else cur
            continue
        cur = os.path.join(cur, part)
        if os.path.lexists(cur):
            cur = os.path.realpath(cur)
    return os.path.realpath(cur)


def resolve_path(path: str) -> str:
    """Absolute against the cwd once, then realpath'd, symlinks before "..".

    Note: os.path.abspath() must NOT run first, since it folds "a/link/.." to "a"
    lexically and realpath would then never see the link. A plain join with the cwd
    keeps the components for realpath. Used for the home (via resolve_home) and for
    every SQLite file path (mesh.core.db.sqlite_uri).
    """
    joined = os.path.join(os.getcwd(), os.fspath(path))
    if sys.platform == "win32" and ".." in re.split(r"[/\\]+", joined):
        return _resolve_path_win(joined)
    return os.path.realpath(joined)


def resolve_home(home: str) -> str:
    """The one home resolution for every entry point (m3-test-kdf round 3).

    Resolved with resolve_path (symlinks followed before ".."), so `a/link/..` is the
    link target's parent (what the kernel opens), not `a`. init, meshd, doctor and the
    CLI --home / MESH_HOME all use this.

    Round 4: an empty or whitespace-only home (`--home ""`) is refused instead of
    silently meaning the cwd, and so is "/" or any home that resolves to "/".
    Both raise INVALID_ARGUMENT (rc 2).
    """
    raw = os.fspath(home) if home is not None else ""
    if isinstance(raw, bytes):
        raw = os.fsdecode(raw)
    if not raw.strip():
        raise MeshError(
            code=c.INVALID_ARGUMENT,
            exit_code=c.EXIT_USAGE,
            message="The Mesh home (--home / MESH_HOME) must not be empty.",
            details={"param": "home", "home": raw},
        )
    resolved = resolve_path(raw)
    if is_fs_root(resolved):
        raise MeshError(
            code=c.INVALID_ARGUMENT,
            exit_code=c.EXIT_USAGE,
            message=f"The Mesh home must not be the filesystem root '/' (given {raw!r}).",
            details={"param": "home", "home": raw, "resolved": resolved},
        )
    return resolved


def default_home_path() -> str:
    """The resolved default home (~/.agent-mesh), as meshd resolves it."""
    return os.path.realpath(os.path.expanduser("~/.agent-mesh"))


def _dir_identity_key(path: str) -> tuple:
    """Filesystem identity of a (resolved) home path, for alias detection.

    Existing directory: ("dir", st_dev, st_ino). Not existing yet: the identity of
    its parent plus its basename, ("name", parent st_dev, parent st_ino, basename).
    If even the parent cannot be stat'ed: ("path", realpath).
    """
    real = os.path.realpath(path)
    try:
        st = os.stat(real)
        return ("dir", st.st_dev, st.st_ino)
    except OSError:
        pass
    if is_fs_root(real):
        parent, name = real, ""
    elif sys.platform == "win32":
        parent, name = os.path.split(real.rstrip("\\/") or os.sep)
    else:
        parent, name = os.path.split(real.rstrip(os.sep) or os.sep)
    try:
        pst = os.stat(parent or os.sep)
        return ("name", pst.st_dev, pst.st_ino, name)
    except OSError:
        return ("path", real)


def is_default_home(home: str) -> bool:
    """True if ``home`` is the default home ~/.agent-mesh, under any alias we can see.

    m3-test-kdf fix round (guard a): the realpath string compare catches symlinks;
    the filesystem identity compare (st_dev, st_ino) also catches a bind mount or
    any second path to the same directory. When the home does not exist yet, the
    parent's identity plus the basename is compared (so a bind-mounted alias of
    the default home's parent is caught too). Out of scope: a user with mount
    rights who mounts something over the default home after this check, or swaps
    directories between the check and init (same-UID / mount-capable attacker).
    """
    default = default_home_path()
    real = os.path.realpath(home)
    if real == default:
        return True
    return _dir_identity_key(real) == _dir_identity_key(default)


def refuse_testing_on_default_home(home: str, testing_mode: bool) -> None:
    """The one default-home guard shared by `mesh init`, meshd and `mesh doctor`.

    Testing mode (MESH_TESTING=1: fake adapter, crash hooks, cheap KDF accepted) is
    refused on the default home ~/.agent-mesh under any alias is_default_home sees.
    Raises INVALID_ARGUMENT (rc 2).
    """
    if testing_mode and is_default_home(home):
        raise MeshError(
            code=c.INVALID_ARGUMENT,
            exit_code=c.EXIT_USAGE,
            message="Testing mode (MESH_TESTING=1) is refused on the default home ~/.agent-mesh; "
                    "set MESH_HOME to a separate directory.",
            details={"param": "MESH_TESTING", "home": os.path.realpath(home)},
        )


def is_path_equal_or_parent(parent: str, child: str) -> bool:
    """Return True if child is equal to parent or located inside parent directory."""
    return _plat_is_path_equal_or_parent(parent, child)


def _strip_win_trailing_seps(path: str) -> str:
    if is_fs_root(path):
        return path
    return path.rstrip("\\/") or os.sep


def has_symlink_component(path: str, stop_at: Optional[str] = None) -> bool:
    """Return True if ``path`` or any ancestor (up to ``stop_at`` when given) is a symlink or junction."""
    if not isinstance(path, str) or not path.strip():
        return True
    if sys.platform == "win32":
        cur = os.path.abspath(_strip_win_trailing_seps(path))
        stop = os.path.abspath(_strip_win_trailing_seps(stop_at)) if stop_at else None
        while True:
            if is_reparse_link(cur):
                return True
            if stop is not None and norm_cmp(cur) == norm_cmp(stop):
                return False
            parent = os.path.dirname(cur)
            if parent == cur:
                return False
            cur = parent
    cur = os.path.abspath(path.rstrip(os.sep) or os.sep)
    stop = os.path.abspath(stop_at.rstrip(os.sep) or os.sep) if stop_at else None
    while True:
        if is_reparse_link(cur):
            return True
        if stop is not None and cur == stop:
            return False
        parent = os.path.dirname(cur)
        if parent == cur:
            return False
        cur = parent


def _win_trusted_paths_match(
    abs_path: str,
    real_path: str,
    *,
    pathmod: Any = ntpath,
    lstat_fn: Callable[[str], Any] = os.lstat,
    is_reparse_stat_fn: Callable[[Any], bool] = is_reparse_stat,
    same_path_fn: Callable[[str, str], bool] = same_path,
) -> bool:
    """Verify Windows ``abs_path`` matches ``real_path`` up to case and non-reparse 8.3 names."""
    abs_norm = _strip_win_extended_prefix(abs_path)
    real_norm = _strip_win_extended_prefix(real_path)
    d_abs, rest_abs = pathmod.splitdrive(abs_norm)
    d_real, rest_real = pathmod.splitdrive(real_norm)
    if pathmod.normcase(d_abs) != pathmod.normcase(d_real):
        return False
    segs_abs = [s for s in rest_abs.replace("/", "\\").split("\\") if s]
    segs_real = [s for s in rest_real.replace("/", "\\").split("\\") if s]
    if len(segs_abs) != len(segs_real):
        return False
    cur_abs = d_abs + ("\\" if d_abs and not d_abs.endswith("\\") else "")
    cur_real = d_real + ("\\" if d_real and not d_real.endswith("\\") else "")
    for seg_a, seg_r in zip(segs_abs, segs_real):
        cur_abs = pathmod.join(cur_abs, seg_a)
        cur_real = pathmod.join(cur_real, seg_r)
        if pathmod.normcase(seg_a) == pathmod.normcase(seg_r):
            continue
        if "~" not in seg_a:
            return False
        try:
            st_a = lstat_fn(cur_abs)
            st_r = lstat_fn(cur_real)
        except OSError:
            return False
        if is_reparse_stat_fn(st_a) or is_reparse_stat_fn(st_r):
            return False
        if st_a.st_ino and st_r.st_ino:
            if st_a.st_dev != st_r.st_dev or st_a.st_ino != st_r.st_ino:
                return False
        if not same_path_fn(cur_abs, cur_real):
            return False
    return True


def _resolve_trusted_one_win(raw_path: Optional[str]) -> Optional[str]:
    if not isinstance(raw_path, str) or not raw_path.strip() or "\x00" in raw_path:
        return None
    if has_traversal_segment_win(raw_path):
        return None
    raw = _strip_win_trailing_seps(raw_path)
    if not raw:
        return None
    abs_path = os.path.abspath(raw)
    if is_fs_root(abs_path) or has_symlink_component(abs_path):
        return None
    real_path = resolve_path(raw)
    if not _win_trusted_paths_match(abs_path, real_path) or has_symlink_component(abs_path):
        return None
    return real_path


def resolve_trusted_path(
    path: Optional[str],
    *,
    root: Optional[str] = None,
    allow_equal: bool = False,
) -> Optional[str]:
    """Resolve ``path`` with ``os.path.realpath`` while rejecting symlinks and root escapes.

    Strips trailing path separators so ``os.path.islink('symlink/')`` cannot bypass checks,
    rejects ``..`` traversal segments and symlinked ancestors, and verifies containment
    within ``root`` (strictly beneath ``root`` unless ``allow_equal=True``).
    """
    if sys.platform == "win32":
        real_path = _resolve_trusted_one_win(path)
        if real_path is None:
            return None
        if root is not None:
            root_real = _resolve_trusted_one_win(root)
            if root_real is None:
                return None
            if norm_cmp(real_path) == norm_cmp(root_real):
                return real_path if allow_equal else None
            if not is_path_equal_or_parent(root_real, real_path):
                return None
        return real_path

    if not isinstance(path, str) or not path.strip() or "\x00" in path:
        return None
    raw = path.rstrip(os.sep)
    if not raw or any(seg == ".." for seg in raw.split(os.sep) if seg):
        return None
    abs_path = os.path.abspath(raw)
    if abs_path == os.sep or has_symlink_component(abs_path):
        return None
    real_path = resolve_path(raw)
    if real_path != abs_path:
        return None
    if root is not None:
        if not isinstance(root, str) or not root.strip() or "\x00" in root:
            return None
        root_raw = root.rstrip(os.sep)
        if not root_raw or any(seg == ".." for seg in root_raw.split(os.sep) if seg):
            return None
        root_abs = os.path.abspath(root_raw)
        if root_abs == os.sep or has_symlink_component(root_abs):
            return None
        root_real = resolve_path(root_raw)
        if root_real != root_abs:
            return None
        if real_path == root_real:
            return real_path if allow_equal else None
        if not is_path_equal_or_parent(root_real, real_path):
            return None
    return real_path


def check_install_path_secure(
    install_root: Optional[str] = None,
    home: Optional[str] = None,
    workspaces_root: Optional[str] = None,
    repo_paths: Optional[List[str]] = None,
) -> None:
    """Verify bidirectionally that the install root does not overlap with workspaces, runs, or repos.

    Per plan §7.6 mitigation 7 and review-r3 minor findings 2 & 4:
    1. The install root MUST NOT be equal to or inside $MESH_HOME (round 6),
       workspaces.root, $MESH_HOME/runs, or any registered project repo root.
    2. Conversely, workspaces.root, $MESH_HOME, $MESH_HOME/runs, and any registered project
       repo root MUST NOT be inside the install root.

    Any overlap in either direction triggers exit 2 INSTALL_PATH_INSECURE with
    details: {'install_root': ..., 'conflict': ...}.
    """
    if install_root is None:
        install_root = get_install_root()
    else:
        install_root = os.path.realpath(install_root)

    candidates: List[tuple[str, str]] = []

    if home is not None:
        home_real = os.path.realpath(home)
        runs_real = os.path.realpath(os.path.join(home, "runs"))
        candidates.append(("home", home_real))
        candidates.append(("runs", runs_real))
        if workspaces_root is None:
            workspaces_root = os.path.join(home, "workspaces")

    if workspaces_root is not None:
        candidates.append(("workspaces.root", os.path.realpath(workspaces_root)))

    if repo_paths:
        for rp in repo_paths:
            if rp:
                candidates.append(("repo", os.path.realpath(rp)))

    for label, target_path in candidates:
        # Check direction 1: install root is equal to or inside target_path (the home
        # itself is checked after the loop, so a more specific conflict is named first).
        if label != "home" and is_path_equal_or_parent(target_path, install_root):
            raise MeshError(
                code=c.INSTALL_PATH_INSECURE,
                exit_code=c.EXIT_USAGE,
                message=f"Install root '{install_root}' is inside or equal to {label} '{target_path}'",
                details={"install_root": install_root, "conflict": target_path},
            )

        # Check direction 2: target_path is equal to or inside install_root
        if is_path_equal_or_parent(install_root, target_path):
            raise MeshError(
                code=c.INSTALL_PATH_INSECURE,
                exit_code=c.EXIT_USAGE,
                message=f"{label} '{target_path}' is inside or equal to install root '{install_root}'",
                details={"install_root": install_root, "conflict": target_path},
            )

    # m3-test-kdf round 6: direction 1 for the home itself too. An install root nested
    # anywhere in $MESH_HOME (e.g. $MESH_HOME/logs/install) is refused, so the home and
    # the install root never overlap in either direction.
    if home is not None and is_path_equal_or_parent(home_real, install_root):
        raise MeshError(
            code=c.INSTALL_PATH_INSECURE,
            exit_code=c.EXIT_USAGE,
            message=f"Install root '{install_root}' is inside or equal to home '{home_real}'",
            details={"install_root": install_root, "conflict": home_real},
        )


def check_home_permissions(home: str) -> None:
    """Verify that MESH_HOME is owned by current uid and permissions are 0700 (mode & 0o077 == 0).

    Per plan §5.1, §15.3, C3, C4:
    If permissions are insecure, raise MeshError(INSECURE_PERMISSIONS, exit_code 2).
    """
    if not os.path.exists(home):
        return

    if sys.platform == "win32":
        try:
            perms.verify_private_owner_and_perms(home, is_dir=True, label=home)
        except OSError as exc:
            raise MeshError(
                code=c.INSECURE_PERMISSIONS,
                exit_code=c.EXIT_USAGE,
                message=f"Storage root '{home}' cannot be verified as a private directory: {exc.strerror or exc}",
                details={"home": home},
            ) from exc
        return

    st = os.stat(home)
    # Check ownership
    if st.st_uid != os.getuid():
        raise MeshError(
            code=c.INSECURE_PERMISSIONS,
            exit_code=c.EXIT_USAGE,
            message=f"Storage root '{home}' is not owned by current uid {os.getuid()}",
            details={"home": home, "owner_uid": st.st_uid, "current_uid": os.getuid()},
        )

    # Check mode & 0o077 == 0 (no group or other read/write/execute permissions)
    if (st.st_mode & 0o077) != 0:
        mode_octal = oct(stat.S_IMODE(st.st_mode))
        raise MeshError(
            code=c.INSECURE_PERMISSIONS,
            exit_code=c.EXIT_USAGE,
            message=f"Storage root '{home}' has insecure permissions {mode_octal} (must be mode 0700)",
            details={"home": home, "mode": mode_octal},
        )


def check_socket_path_length(socket_path: str) -> None:
    """Verify Unix domain socket path length does not exceed 107 bytes per plan §5.1."""
    encoded_len = len(socket_path.encode("utf-8"))
    if encoded_len > 107:
        raise MeshError(
            code=c.SOCKET_PATH_TOO_LONG,
            exit_code=c.EXIT_USAGE,
            message=f"Unix socket path length ({encoded_len} bytes) exceeds maximum limit of 107 bytes: '{socket_path}'",
            details={"socket_path": socket_path, "bytes": encoded_len, "limit": 107},
        )


def _open_token_file_secure(
    token_file: str,
    home: str,
    workspaces_root: Optional[str] = None,
    repo_paths: Optional[List[str]] = None,
) -> int:
    """Open *token_file* without following symlinks and validate type, owner, mode, and location."""
    if sys.platform == "win32":
        try:
            fd = open_regular_nofollow(token_file, os.O_RDONLY, label="token file")
        except FileNotFoundError:
            raise MeshError(
                code=c.TOKEN_FILE_INSECURE,
                exit_code=c.EXIT_UNAUTHENTICATED,
                message=f"Token file '{token_file}' does not exist",
                details={"token_file": token_file},
            )
        except OSError as exc:
            if exc.errno == errno.ELOOP:
                raise MeshError(
                    code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                    message=f"Token file '{token_file}' cannot be a symlink",
                    details={"token_file": token_file},
                ) from exc
            if exc.errno in (errno.EINVAL, errno.EISDIR):
                raise MeshError(
                    code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                    message=f"Token file '{token_file}' must be a regular file",
                    details={"token_file": token_file},
                ) from exc
            raise MeshError(
                code=c.TOKEN_FILE_INSECURE,
                exit_code=c.EXIT_UNAUTHENTICATED,
                message=f"Token file '{token_file}' cannot be opened securely: {exc.strerror or exc}",
                details={"token_file": token_file},
            ) from exc
    else:
        flags = os.O_RDONLY | os.O_NOFOLLOW | getattr(os, "O_NONBLOCK", 0)
        try:
            fd = os.open(token_file, flags)
        except FileNotFoundError:
            raise MeshError(
                code=c.TOKEN_FILE_INSECURE,
                exit_code=c.EXIT_UNAUTHENTICATED,
                message=f"Token file '{token_file}' does not exist",
                details={"token_file": token_file},
            )
        except OSError as exc:
            if exc.errno == errno.ELOOP:
                raise MeshError(
                    code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                    message=f"Token file '{token_file}' cannot be a symlink",
                    details={"token_file": token_file},
                ) from exc
            raise MeshError(
                code=c.TOKEN_FILE_INSECURE,
                exit_code=c.EXIT_UNAUTHENTICATED,
                message=f"Token file '{token_file}' cannot be opened securely: {exc.strerror or exc}",
                details={"token_file": token_file},
            ) from exc

    try:
        if sys.platform == "win32":
            try:
                perms.verify_private_owner_and_perms(
                    fd,
                    is_dir=False,
                    label=token_file,
                    error_code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                )
            except OSError as exc:
                raise MeshError(
                    code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                    message=f"Token file '{token_file}' must be a regular file",
                    details={"token_file": token_file},
                ) from exc
        else:
            st = os.fstat(fd)
            if not stat.S_ISREG(st.st_mode):
                raise MeshError(
                    code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                    message=f"Token file '{token_file}' must be a regular file",
                    details={"token_file": token_file},
                )
            uid = os.getuid()
            if st.st_uid != uid:
                raise MeshError(
                    code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                    message=f"Token file '{token_file}' is not owned by current uid {uid}",
                    details={"token_file": token_file, "owner_uid": st.st_uid, "current_uid": uid},
                )
            if (st.st_mode & 0o077) != 0:
                mode_octal = oct(stat.S_IMODE(st.st_mode))
                raise MeshError(
                    code=c.TOKEN_FILE_INSECURE,
                    exit_code=c.EXIT_UNAUTHENTICATED,
                    message=f"Token file '{token_file}' has insecure permissions {mode_octal} (must be mode 0600)",
                    details={"token_file": token_file, "mode": mode_octal},
                )

        # Check location
        token_real = os.path.realpath(token_file)
        runs_dir = os.path.realpath(os.path.join(home, "runs"))
        if is_path_equal_or_parent(runs_dir, token_real):
            raise MeshError(
                code=c.TOKEN_FILE_INSECURE,
                exit_code=c.EXIT_UNAUTHENTICATED,
                message=f"Token file '{token_file}' cannot be located inside runs directory '{runs_dir}'",
                details={"token_file": token_file, "conflict": runs_dir},
            )

        if workspaces_root is None:
            workspaces_root = os.path.join(home, "workspaces")
        ws_real = os.path.realpath(workspaces_root)
        if is_path_equal_or_parent(ws_real, token_real):
            raise MeshError(
                code=c.TOKEN_FILE_INSECURE,
                exit_code=c.EXIT_UNAUTHENTICATED,
                message=f"Token file '{token_file}' cannot be located inside workspaces root '{ws_real}'",
                details={"token_file": token_file, "conflict": ws_real},
            )

        if repo_paths:
            for rp in repo_paths:
                if rp and is_path_equal_or_parent(os.path.realpath(rp), token_real):
                    raise MeshError(
                        code=c.TOKEN_FILE_INSECURE,
                        exit_code=c.EXIT_UNAUTHENTICATED,
                        message=f"Token file '{token_file}' cannot be located inside repository '{rp}'",
                        details={"token_file": token_file, "conflict": rp},
                    )
        return fd
    except BaseException:
        os.close(fd)
        raise


def check_token_file_secure(
    token_file: str,
    home: str,
    workspaces_root: Optional[str] = None,
    repo_paths: Optional[List[str]] = None,
) -> None:
    """Verify agent token file permissions and path security per plan §7.1, §7.6 mitigation 2, C10, C12."""
    fd = _open_token_file_secure(
        token_file, home=home, workspaces_root=workspaces_root, repo_paths=repo_paths
    )
    os.close(fd)


def read_token_file_secure(
    token_file: str,
    home: str,
    workspaces_root: Optional[str] = None,
    repo_paths: Optional[List[str]] = None,
    *,
    max_bytes: int = 16384,
) -> str:
    """Validate and read a token file via one O_NOFOLLOW file descriptor (no TOCTOU)."""
    fd = _open_token_file_secure(
        token_file, home=home, workspaces_root=workspaces_root, repo_paths=repo_paths
    )
    with os.fdopen(fd, "r", encoding="utf-8", errors="strict") as f:
        try:
            content = f.read(max_bytes + 1)
        except (OSError, UnicodeDecodeError) as exc:
            raise MeshError(
                code=c.TOKEN_INVALID,
                exit_code=c.EXIT_UNAUTHENTICATED,
                message=f"Failed to read token file '{token_file}': {exc}",
            ) from exc
    if len(content) > max_bytes:
        raise MeshError(
            code=c.TOKEN_INVALID,
            exit_code=c.EXIT_UNAUTHENTICATED,
            message=f"Token file '{token_file}' is unexpectedly large",
        )
    return content.strip()


def make_owned_dirs_writable(
    target: str,
    boundary_real: Optional[str] = None,
    skip_names: Optional[Set[str]] = None,
    skip_paths_real: Optional[Set[str]] = None,
) -> bool:
    """Safely add ``0o700`` on owned, non-symlinked directories under ``target``.

    Never follows symlinks and never modifies directories outside ``boundary_real``
    (which defaults to ``os.path.realpath(target)``). Returns True if any directory
    permission bits were changed.
    """
    uid = os.getuid() if hasattr(os, "getuid") else None
    bound_real = os.path.realpath(boundary_real) if boundary_real else os.path.realpath(target)
    skip_cmp = {norm_cmp(p) for p in skip_paths_real} if skip_paths_real else None
    changed = False
    stack = [target]
    while stack:
        cur = stack.pop()
        try:
            st = os.lstat(cur)
        except OSError:
            continue
        if is_reparse_stat(st) or not stat.S_ISDIR(st.st_mode):
            continue
        cur_real = os.path.realpath(cur)
        if not is_path_equal_or_parent(bound_real, cur_real):
            continue
        if skip_cmp and norm_cmp(cur_real) in skip_cmp:
            continue
        if uid is not None or sys.platform == "win32":
            try:
                if perms.ensure_owned_dir_writable(cur, st=st, uid=uid):
                    changed = True
            except OSError:
                continue
        else:
            if not (st.st_mode & stat.S_IWRITE):
                try:
                    os.chmod(cur, stat.S_IWRITE)
                    changed = True
                except OSError:
                    continue
        try:
            with os.scandir(cur) as it:
                for entry in it:
                    try:
                        if skip_names and entry.name in skip_names:
                            continue
                        if not is_reparse_link(entry.path) and entry.is_dir(follow_symlinks=False):
                            child_real = os.path.realpath(entry.path)
                            if skip_cmp and norm_cmp(child_real) in skip_cmp:
                                continue
                            if is_path_equal_or_parent(bound_real, child_real):
                                stack.append(entry.path)
                    except OSError:
                        continue
        except OSError:
            continue
    return changed


def make_owned_ancestors_writable(target: str, boundary_real: str) -> bool:
    """Safely add ``0o700`` on owned non-symlinked ancestor dirs strictly inside ``boundary_real``."""
    if not isinstance(target, str) or not target.strip() or "\x00" in target:
        return False
    bound_real = resolve_trusted_path(boundary_real, allow_equal=True)
    if bound_real is None:
        return False
    try:
        bound_st = os.lstat(bound_real)
    except OSError:
        return False
    if is_reparse_stat(bound_st) or not stat.S_ISDIR(bound_st.st_mode):
        return False

    if sys.platform == "win32":
        if is_fs_root(bound_real) or has_traversal_segment_win(target):
            return False
        raw_target = _strip_win_trailing_seps(target)
    else:
        raw_target = target.rstrip(os.sep)
        if not raw_target or any(seg == ".." for seg in raw_target.split(os.sep) if seg):
            return False
    if not raw_target:
        return False
    abs_target = os.path.abspath(raw_target)
    parent_abs = os.path.dirname(abs_target)
    if sys.platform == "win32":
        if norm_cmp(parent_abs) == norm_cmp(bound_real) or not is_path_equal_or_parent(bound_real, parent_abs):
            return False
    elif parent_abs == bound_real or not parent_abs.startswith(bound_real + os.sep):
        return False

    rel = os.path.relpath(parent_abs, bound_real)
    parts = [p for p in rel.split(os.sep) if p and p != "."]
    if not parts or any(p == ".." for p in parts):
        return False

    uid = os.getuid() if hasattr(os, "getuid") else None
    changed = False
    cur = bound_real
    for part in parts:
        cur = os.path.join(cur, part)
        try:
            st = os.lstat(cur)
        except OSError:
            break
        if is_reparse_stat(st) or not stat.S_ISDIR(st.st_mode):
            return False
        cur_real = os.path.realpath(cur)
        if norm_cmp(cur_real) == norm_cmp(bound_real) or not is_path_equal_or_parent(bound_real, cur_real):
            return False
        if uid is not None or sys.platform == "win32":
            try:
                if perms.ensure_owned_dir_writable(cur, st=st, uid=uid):
                    changed = True
            except OSError:
                break
        else:
            if not (st.st_mode & stat.S_IWRITE):
                try:
                    os.chmod(cur, stat.S_IWRITE)
                    changed = True
                except OSError:
                    break
    return changed


def rmtree_allow_readonly(target: str, boundary_real: Optional[str] = None) -> None:
    """Remove ``target`` directory tree, fixing owned read-only dirs/files strictly inside boundary."""
    trusted = resolve_trusted_path(target, root=boundary_real, allow_equal=True)
    if trusted is None:
        raise OSError(errno.EINVAL, "Refusing to remove symlink or untrusted path", target)
    if is_reparse_link(trusted):
        raise OSError(errno.EINVAL, "Refusing to remove symlink", target)
    if sys.platform == "win32":
        bound_real = resolve_trusted_path(boundary_real, allow_equal=True) if boundary_real else trusted
        if bound_real is None:
            raise OSError(errno.EINVAL, "Refusing to remove symlink or untrusted path", target)

        def _on_win_exc(func: Any, exc_path: str, exc: BaseException) -> None:
            winerr = getattr(exc, "winerror", None)
            if not isinstance(exc, PermissionError) and winerr not in (5, 32):
                raise exc
            if is_reparse_link(exc_path):
                raise exc
            if has_symlink_component(exc_path, stop_at=trusted):
                raise exc
            if not is_path_equal_or_parent(bound_real, exc_path):
                raise exc
            try:
                owned = perms.is_owned_by_current_user(exc_path)
            except OSError:
                raise exc
            if not owned:
                raise exc
            delays = (0.005, 0.015, 0.030) if winerr in (5, 32) else ()
            for idx in range(len(delays) + 1):
                try:
                    os.chmod(exc_path, stat.S_IWRITE)
                except OSError as chmod_exc:
                    if idx >= len(delays) or getattr(chmod_exc, "winerror", None) not in (5, 32):
                        if winerr not in (5, 32):
                            raise chmod_exc from exc
                try:
                    func(exc_path)
                    return
                except OSError as retry_exc:
                    if idx >= len(delays) or getattr(retry_exc, "winerror", None) not in (5, 32):
                        raise
                    time.sleep(delays[idx])

        shutil.rmtree(trusted, onexc=_on_win_exc)
    else:
        try:
            shutil.rmtree(trusted)
        except PermissionError:
            trusted_retry = resolve_trusted_path(target, root=boundary_real, allow_equal=True)
            if trusted_retry is None or trusted_retry != trusted:
                raise OSError(errno.EINVAL, "Refusing to remove symlink or untrusted path", target)
            if not make_owned_dirs_writable(trusted_retry, boundary_real=boundary_real):
                raise
            trusted_after_chmod = resolve_trusted_path(target, root=boundary_real, allow_equal=True)
            if trusted_after_chmod is None or trusted_after_chmod != trusted:
                raise OSError(errno.EINVAL, "Refusing to remove symlink or untrusted path", target)
            shutil.rmtree(trusted_after_chmod)
    post = resolve_trusted_path(target, root=boundary_real, allow_equal=True)
    if post is None or norm_cmp(post) != norm_cmp(trusted):
        raise OSError(errno.EINVAL, "Path escaped boundary during removal", target)


def autostart_hold_path(home: str) -> str:
    """Path to the home-level marker suppressing desktop supervisor auto-restart after explicit stop."""
    return os.path.join(home, "run", "autostart.hold")


def write_autostart_hold(
    home: str,
    *,
    pid: Optional[int] = None,
    boot_id: Optional[str] = None,
    source: str = "stop",
) -> None:
    """Atomically write ``$MESH_HOME/run/autostart.hold`` (best-effort, symlink-safe)."""
    import json
    import tempfile

    if not home or not os.path.isdir(home):
        return
    run_dir = os.path.join(home, "run")
    path = autostart_hold_path(home)
    try:
        existed = os.path.isdir(run_dir)
        os.makedirs(run_dir, mode=0o700, exist_ok=True)
        if sys.platform == "win32" and not existed:
            perms.set_private_dir_acl(run_dir, 0o700)
        payload = json.dumps(
            {
                "source": str(source or "stop"),
                "pid": pid if isinstance(pid, int) else None,
                "boot_id": str(boot_id) if isinstance(boot_id, str) and boot_id else None,
                "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            },
            separators=(",", ":"),
        )
        fd, tmp = tempfile.mkstemp(dir=run_dir, prefix=".autostart-hold-")
        try:
            if sys.platform == "win32":
                perms.fchmod_private(fd, 0o600)
            else:
                os.chmod(tmp, 0o600)
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                f.write(payload + "\n")
            atomic_replace(tmp, path)
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise
    except OSError:
        pass


def read_autostart_hold(home: str) -> Optional[dict]:
    """Return parsed metadata if ``$MESH_HOME/run/autostart.hold`` exists (regular file), else None."""
    import json

    if not home:
        return None
    path = autostart_hold_path(home)
    if not os.path.isfile(path) or is_reparse_link(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            doc = json.loads(f.read())
        return doc if isinstance(doc, dict) else {}
    except (OSError, ValueError):
        return {}


def clear_autostart_hold(home: str) -> None:
    """Remove ``$MESH_HOME/run/autostart.hold`` if present (best-effort)."""
    if not home:
        return
    try:
        os.unlink(autostart_hold_path(home))
    except FileNotFoundError:
        pass
    except OSError:
        pass

